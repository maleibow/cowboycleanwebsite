// Keeps the <link rel="modulepreload"> block in cleaningup3d.html in step with the game's static import graph.
//   node tools/preload.mjs          rewrite the block
//   node tools/preload.mjs --check  exit 1 if the block is stale (run by tools/smoke.mjs)
// Why: the browser discovers ES modules one import level at a time (a waterfall of ~8 round trips for ~200 files). Listing them all
// in the HTML lets it fetch them in parallel, which is most of the time-to-interactive-title on a phone connection.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = path.join(root, 'cleaningup3d.html');
const IMPORT = /(?:^|\n)\s*(?:import|export)\s+(?:[^'"\n;]*?\sfrom\s*)?['"]([^'"]+)['"]/g;
const seen = new Set(), order = [];
const resolve = (spec, from) => {
  if (spec === 'three') return path.join(root, 'game3d/vendor/three.module.min.js');
  if (spec.startsWith('three/addons/')) return path.join(root, 'game3d/vendor/addons', spec.slice('three/addons/'.length));
  if (spec.startsWith('.')) return path.resolve(path.dirname(from), spec);
  return null;
};
const visit = (file) => {
  if (seen.has(file) || !fs.existsSync(file)) return; seen.add(file); order.push(file);
  const src = fs.readFileSync(file, 'utf8'); let m; IMPORT.lastIndex = 0;
  while ((m = IMPORT.exec(src))) { const f = resolve(m[1], file); if (f) visit(f); }
};
visit(path.join(root, 'game3d/main.js'));
visit(path.join(root, 'game3d/vendor/three.core.min.js'));            // imported by three.module.min.js through its own relative import
const urls = order.map((f) => './' + path.relative(root, f).split(path.sep).join('/'));
const block = '<!-- modulepreload:start (generated by tools/preload.mjs) -->\n' + urls.map((u) => `    <link rel="modulepreload" href="${u}" />`).join('\n') + '\n    <!-- modulepreload:end -->';
const cur = fs.readFileSync(html, 'utf8'), re = /<!-- modulepreload:start[\s\S]*?<!-- modulepreload:end -->/;
let next;
if (re.test(cur)) next = cur.replace(re, block);
else next = cur.replace('</head>', `    ${block}\n  </head>`);
if (process.argv.includes('--check')) { if (next !== cur) { console.error('modulepreload block is stale: run node tools/preload.mjs'); process.exit(1); } console.log(`modulepreload block is current (${urls.length} modules)`); }
else { fs.writeFileSync(html, next); console.log(`modulepreload block written (${urls.length} modules)`); }
